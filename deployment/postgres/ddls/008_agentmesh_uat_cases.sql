CREATE TABLE IF NOT EXISTS agentmesh_uat_cases (
    case_id TEXT PRIMARY KEY,
    suite TEXT NOT NULL CHECK (suite IN ('smoke', 'unit', 'validation', 'uat')),
    component TEXT NOT NULL,
    category TEXT NOT NULL,
    test_type TEXT NOT NULL,
    execution_layer TEXT NOT NULL CHECK (
        execution_layer IN ('streamlit', 'api', 'worker', 'postgres', 'docker', 'langsmith')
    ),
    command_hint TEXT NOT NULL,
    streamlit_surface TEXT NOT NULL DEFAULT '',
    expected TEXT NOT NULL,
    priority TEXT NOT NULL CHECK (priority IN ('P0', 'P1', 'P2')),
    langsmith_eval BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_agentmesh_uat_cases_suite_priority
    ON agentmesh_uat_cases (suite, priority, case_id)
    WHERE active = TRUE;

CREATE INDEX IF NOT EXISTS idx_agentmesh_uat_cases_execution_layer
    ON agentmesh_uat_cases (execution_layer, component)
    WHERE active = TRUE;

