CREATE OR REPLACE VIEW v_agentmesh_uat_case_summary AS
SELECT suite, execution_layer, priority, COUNT(*) AS case_count
FROM agentmesh_uat_cases
WHERE active = TRUE
GROUP BY suite, execution_layer, priority;

CREATE OR REPLACE VIEW v_agentmesh_langsmith_eval_cases AS
SELECT *
FROM agentmesh_uat_cases
WHERE active = TRUE AND langsmith_eval = TRUE;
